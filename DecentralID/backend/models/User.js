const bcrypt = require('bcryptjs');
const { getDB } = require('../config/database');

function optionsWithSession(options, session) {
    return session ? { ...options, session } : options;
}

class User {
    /**
     * Create a new university user
     */
    static async createUniversity(email, password, universityName) {
        const db = getDB();
        const hashedPassword = await bcrypt.hash(password, 10);

        const university = {
            email: email.toLowerCase().trim(),
            password: hashedPassword,
            universityName,
            role: 'university',
            createdAt: new Date()
        };

        const result = await db.collection('universities').insertOne(university);
        return result;
    }

    /**
     * Upsert university user (create or update password)
     */
    static async upsertUniversity(email, password, universityName) {
        const db = getDB();
        const cleanEmail = email.toLowerCase().trim();
        const hashedPassword = await bcrypt.hash(password, 10);

        await db.collection('universities').updateOne(
            { email: cleanEmail },
            {
                $set: {
                    email: cleanEmail,
                    password: hashedPassword,
                    universityName,
                    role: 'university',
                    updatedAt: new Date()
                },
                $setOnInsert: { createdAt: new Date() }
            },
            { upsert: true }
        );
        return await db.collection('universities').findOne({ email: cleanEmail });
    }

    /**
     * Create a new verifier user
     */
    static async createVerifier(orgId, password, organizationName) {
        const db = getDB();
        const hashedPassword = await bcrypt.hash(password, 10);

        const verifier = {
            orgId: orgId.trim(),
            password: hashedPassword,
            organizationName,
            role: 'verifier',
            createdAt: new Date()
        };

        const result = await db.collection('verifiers').insertOne(verifier);
        return result;
    }

    /** Create or refresh a verifier account from the configured credentials. */
    static async upsertVerifier(orgId, password, organizationName) {
        const db = getDB();
        const cleanOrgId = orgId.trim();
        const hashedPassword = await bcrypt.hash(password, 10);

        await db.collection('verifiers').updateOne(
            { orgId: cleanOrgId },
            {
                $set: {
                    orgId: cleanOrgId,
                    password: hashedPassword,
                    organizationName,
                    role: 'verifier',
                    updatedAt: new Date()
                },
                $setOnInsert: { createdAt: new Date() }
            },
            { upsert: true }
        );

        return await db.collection('verifiers').findOne({ orgId: cleanOrgId });
    }

    /**
     * Find university by email
     */
    static async findUniversityByEmail(email) {
        const db = getDB();
        return await db.collection('universities').findOne({ email: email.toLowerCase().trim() });
    }

    /**
     * Find verifier by organization ID
     */
    static async findVerifierByOrgId(orgId) {
        const db = getDB();
        return await db.collection('verifiers').findOne({ orgId: orgId.trim() });
    }

    /**
     * Verify password
     */
    static async verifyPassword(plainPassword, hashedPassword) {
        return await bcrypt.compare(plainPassword, hashedPassword);
    }

    /* ==========================================================================
       STUDENT IDENTITY & CREDENTIAL ENROLLMENT
       ========================================================================== */

    /**
     * Enroll or update a student user with DID and login credentials
     */
    static async enrollStudent(studentData, session = null) {
        const db = getDB();
        const cleanEnrollment = (studentData.enrollmentNo || '').trim().toUpperCase();
        const cleanEmail = (studentData.email || '').trim().toLowerCase();
        if (!studentData.password) {
            throw new Error('A student password must be generated by the enrollment service');
        }
        const hashedPassword = await bcrypt.hash(studentData.password, 10);

        const student = {
            enrollmentNo: cleanEnrollment,
            email: cleanEmail,
            name: (studentData.name || '').trim(),
            program: studentData.program || 'B.Tech Computer Science & Engineering',
            graduationYear: studentData.graduationYear || 2027,
            institution: studentData.institution || 'MIT Art, Design and Technology University, Pune',
            courses: Array.isArray(studentData.courses) ? studentData.courses : [],
            gpa: studentData.gpa ?? null,
            did: studentData.did,
            password: hashedPassword,
            role: 'student',
            updatedAt: new Date()
        };

        await db.collection('students').updateOne(
            { enrollmentNo: cleanEnrollment },
            {
                $set: student,
                $setOnInsert: { createdAt: new Date() }
            },
            optionsWithSession({ upsert: true }, session)
        );

        return await db.collection('students').findOne(
            { enrollmentNo: cleanEnrollment },
            optionsWithSession({}, session)
        );
    }

    /**
     * Find student by Enrollment Number (case-insensitive)
     */
    static async findStudentByEnrollmentNo(enrollmentNo) {
        const db = getDB();
        const cleanEnrollment = (enrollmentNo || '').trim().toUpperCase();
        return await db.collection('students').findOne({ enrollmentNo: cleanEnrollment });
    }

    /**
     * Find student by registered Email
     */
    static async findStudentByEmail(email) {
        const db = getDB();
        const cleanEmail = (email || '').trim().toLowerCase();
        return await db.collection('students').findOne({ email: cleanEmail });
    }

    /**
     * Find student by Enrollment Number OR Email
     */
    static async findStudentByEnrollmentOrEmail(identifier) {
        const db = getDB();
        const clean = (identifier || '').trim();
        const cleanEnrollment = clean.toUpperCase();
        const cleanEmail = clean.toLowerCase();

        return await db.collection('students').findOne({
            $or: [
                { enrollmentNo: cleanEnrollment },
                { email: cleanEmail }
            ]
        });
    }

    /**
     * Update student password
     */
    static async updateStudentPassword(enrollmentNo, newPassword, session = null) {
        const hashedPassword = await bcrypt.hash(newPassword, 10);
        return await User.setStudentPasswordHash(enrollmentNo, hashedPassword, session);
    }

    /** Write an already-hashed password so a retried transaction cannot hash it twice. */
    static async setStudentPasswordHash(enrollmentNo, hashedPassword, session = null) {
        const db = getDB();
        const cleanEnrollment = (enrollmentNo || '').trim().toUpperCase();

        await db.collection('students').updateOne(
            { enrollmentNo: cleanEnrollment },
            {
                $set: {
                    password: hashedPassword,
                    updatedAt: new Date()
                }
            },
            optionsWithSession({}, session)
        );
        return true;
    }

    /** Update non-secret student profile fields without changing their password. */
    static async updateStudentProfile(enrollmentNo, studentData) {
        const db = getDB();
        const cleanEnrollment = (enrollmentNo || '').trim().toUpperCase();
        const update = { updatedAt: new Date() };

        if (studentData.email) update.email = studentData.email.trim().toLowerCase();
        if (studentData.name) update.name = studentData.name.trim();
        if (studentData.program) update.program = studentData.program;
        if (studentData.graduationYear) update.graduationYear = studentData.graduationYear;
        if (studentData.institution) update.institution = studentData.institution;
        if (Array.isArray(studentData.courses)) update.courses = studentData.courses;
        if (studentData.gpa !== undefined) update.gpa = studentData.gpa;
        if (studentData.did !== undefined) update.did = studentData.did;

        const result = await db.collection('students').updateOne(
            { enrollmentNo: cleanEnrollment },
            { $set: update }
        );
        if (result.matchedCount === 0) return null;
        return await db.collection('students').findOne({ enrollmentNo: cleanEnrollment });
    }

    /** Persist a signed credential so the recipient can retrieve it on another device. */
    static async saveCredential(credential, session = null) {
        if (!credential?.id || !credential?.credentialSubject?.id || !credential?.proof) {
            throw new Error('A signed credential with an id and subject is required');
        }

        const db = getDB();
        const subject = credential.credentialSubject;
        const enrollmentNo = String(subject.enrollmentNo || subject.prn || '').trim().toUpperCase();
        const email = String(subject.email || '').trim().toLowerCase();

        await db.collection('credentials').updateOne(
            { id: credential.id },
            {
                $set: {
                    ...credential,
                    recipientEnrollmentNo: enrollmentNo,
                    recipientEmail: email,
                    updatedAt: new Date()
                },
                $setOnInsert: { createdAt: new Date() }
            },
            optionsWithSession({ upsert: true }, session)
        );

        if (enrollmentNo) {
            await db.collection('students').updateOne(
                { enrollmentNo },
                { $set: { lastCredentialId: credential.id, updatedAt: new Date() } },
                optionsWithSession({}, session)
            );
        }
    }

    /** Return only credentials addressed to the authenticated student. */
    static async listCredentialsForStudent(student) {
        const db = getDB();
        const enrollmentNo = String(student?.enrollmentNo || '').trim().toUpperCase();
        const email = String(student?.email || '').trim().toLowerCase();
        const did = student?.did || '';
        const filters = [];

        if (enrollmentNo) {
            filters.push({ recipientEnrollmentNo: enrollmentNo });
            filters.push({ 'credentialSubject.enrollmentNo': enrollmentNo });
            filters.push({ 'credentialSubject.prn': enrollmentNo });
        }
        if (email) {
            filters.push({ recipientEmail: email });
            filters.push({ 'credentialSubject.email': email });
        }
        if (did) filters.push({ 'credentialSubject.id': did });
        if (filters.length === 0) return [];

        return await db.collection('credentials')
            .find({ $or: filters }, {
                projection: { _id: 0, createdAt: 0, updatedAt: 0, recipientEnrollmentNo: 0, recipientEmail: 0 }
            })
            .toArray();
    }

    /** Return credentials issued by the authenticated university. */
    static async listCredentialsForIssuer(issuerDID) {
        const db = getDB();
        const filter = issuerDID ? { issuer: issuerDID } : {};
        return await db.collection('credentials')
            .find(filter, { projection: { _id: 0, createdAt: 0, updatedAt: 0, recipientEnrollmentNo: 0, recipientEmail: 0 } })
            .sort({ issuanceDate: -1 })
            .toArray();
    }

    /** Resolve a credential intentionally shared via a compact verification QR. */
    static async findPublicCredentialById(id) {
        const db = getDB();
        return await db.collection('credentials').findOne(
            { id },
            { projection: { _id: 0, createdAt: 0, updatedAt: 0, recipientEnrollmentNo: 0, recipientEmail: 0 } }
        );
    }

    /** Persist a holder-created selective presentation for its compact QR reference. */
    static async saveSelectivePresentation(presentation, holderDID, session = null) {
        if (!presentation?.id || !presentation?.credentialId || !presentation?.disclosedAttributes || !presentation?.proofs) {
            throw new Error('A complete selective presentation is required');
        }

        const db = getDB();
        const credential = await db.collection('credentials').findOne(
            { id: presentation.credentialId },
            optionsWithSession({ projection: { 'credentialSubject.id': 1 } }, session)
        );
        if (!credential) throw new Error('The source credential could not be found');
        if (holderDID && credential.credentialSubject?.id !== holderDID) {
            throw new Error('You may only share a credential issued to your DID');
        }

        await db.collection('selective_presentations').updateOne(
            { id: presentation.id },
            {
                $set: {
                    ...presentation,
                    holderDID: holderDID || credential.credentialSubject?.id || '',
                    updatedAt: new Date()
                },
                $setOnInsert: { createdAt: new Date() }
            },
            optionsWithSession({ upsert: true }, session)
        );
    }

    /** Resolve a selective presentation intentionally shared via its compact QR. */
    static async findPublicSelectivePresentationById(id) {
        const db = getDB();
        return await db.collection('selective_presentations').findOne(
            { id },
            { projection: { _id: 0, createdAt: 0, updatedAt: 0, holderDID: 0 } }
        );
    }

    static async deleteCredential(id) {
        const db = getDB();
        return await db.collection('credentials').deleteOne({ id });
    }

    /**
     * List all enrolled students
     */
    static async listStudents() {
        const db = getDB();
        return await db.collection('students').find({}, { projection: { password: 0 } }).toArray();
    }

    /** Permanently remove a student account by enrollment number. */
    static async deleteStudent(enrollmentNo, session = null) {
        const db = getDB();
        const cleanEnrollment = enrollmentNo.trim().toUpperCase();
        const result = await db.collection('students').deleteOne(
            { enrollmentNo: cleanEnrollment },
            optionsWithSession({}, session)
        );
        await db.collection('dids').deleteMany(
            { ownerEnrollmentNo: cleanEnrollment },
            optionsWithSession({}, session)
        );
        return result;
    }

    /** Permanently remove every enrolled student account and the DIDs they own. */
    static async deleteAllStudents(session = null) {
        const db = getDB();
        const result = await db.collection('students').deleteMany({}, optionsWithSession({}, session));
        await db.collection('dids').deleteMany(
            { ownerRole: 'student' },
            optionsWithSession({}, session)
        );
        return result;
    }

    /**
     * Store a DID document, including signing keys, so the holder can use it
     * from another browser. Keys stay in MongoDB and are not written to the client.
     */
    static async saveDid(didRecord, owner, session = null) {
        if (!didRecord?.id || !didRecord?.keys?.public || !didRecord?.keys?.private) {
            throw new Error('A complete DID with signing keys is required');
        }

        const db = getDB();
        const doc = {
            id: String(didRecord.id),
            alias: didRecord.alias || 'Identity',
            keys: didRecord.keys,
            created: didRecord.created || new Date().toISOString(),
            ownerRole: owner?.role || 'university',
            ownerEmail: owner?.email ? String(owner.email).trim().toLowerCase() : null,
            ownerEnrollmentNo: owner?.enrollmentNo ? String(owner.enrollmentNo).trim().toUpperCase() : null,
            updatedAt: new Date()
        };

        await db.collection('dids').updateOne(
            { id: doc.id },
            { $set: doc, $setOnInsert: { createdAt: new Date() } },
            optionsWithSession({ upsert: true }, session)
        );
        return doc;
    }

    /** Point an existing DID at the student who will sign in with it. */
    static async assignDidOwner(did, owner, session = null) {
        if (!did) return null;
        const db = getDB();
        await db.collection('dids').updateOne(
            { id: did },
            {
                $set: {
                    ownerRole: owner?.role || 'student',
                    ownerEmail: owner?.email ? String(owner.email).trim().toLowerCase() : null,
                    ownerEnrollmentNo: owner?.enrollmentNo ? String(owner.enrollmentNo).trim().toUpperCase() : null,
                    updatedAt: new Date()
                }
            },
            optionsWithSession({}, session)
        );
        return await db.collection('dids').findOne({ id: did }, optionsWithSession({ projection: { _id: 0 } }, session));
    }

    static async findDidById(id, session = null) {
        if (!id) return null;
        const db = getDB();
        return await db.collection('dids').findOne(
            { id },
            optionsWithSession({ projection: { _id: 0 } }, session)
        );
    }

    static async findIssuerDid(email) {
        const db = getDB();
        const ownerEmail = String(email || '').trim().toLowerCase();
        return await db.collection('dids').findOne(
            { ownerEmail, ownerRole: 'university', alias: 'MIT-ADT Issuer' },
            { projection: { _id: 0, createdAt: 0, updatedAt: 0 } }
        );
    }

    static callerOwnsDid(user, did) {
        if (!user || !did) return false;
        if (user.role === 'university') {
            return did.ownerRole === 'university' && did.ownerEmail === String(user.email || '').toLowerCase();
        }
        if (user.role === 'student') {
            const enrollmentNo = String(user.enrollmentNo || '').toUpperCase();
            return did.id === user.did || did.ownerEnrollmentNo === enrollmentNo;
        }
        return false;
    }

    static toPublicDid(did) {
        if (!did) return null;
        return {
            id: did.id,
            alias: did.alias || null,
            created: did.created || null
        };
    }

    static async deleteOwnedDid(id, session = null) {
        const db = getDB();
        return await db.collection('dids').deleteOne({ id }, optionsWithSession({}, session));
    }
}

module.exports = User;
